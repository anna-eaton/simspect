#!/usr/bin/env python3
"""make_campaign_configs.py — gem5 run configs for the two-stage STT_6 fanout-v2 campaigns.

2026-11-09, simspect-c8 (Anna: "giant fanout v2 with all the stops" + "FP fanned out in a separate
instance right next to it", Stage 2 + gem5 sample on every STT-family eval build).

For every eval row below, and for each testset (STT_6_fv2 = all approved fanout options;
STT_6_fv2fp = the same plus fpr routing), copy the row's canonical run config and change only:
  paths.testset_dir    -> testsets_twostage            (two-stage STT_6, 93,041 deduped programs)
  paths.results_name   -> <row>_<testset>
  paths.instruction_tables -> proposed/fv2_vocab.jsonc (record of what Stage 2 used)
  gem5.scheme          -> the row's scheme (E1 0, E8 1, E9 3; others unchanged)
  gem5.sample_fraction -> --sample (0.01 first; the 0.02 top-up is a superset, gem5_common.sample_keep)
  gem5.jobs            -> --jobs
  alloy.max_instances  -> --expected (93,041; testrun.py's completion check compares asm count to it)
  sweep.unresolved_stall_per_branch -> random per-branch unresolved stall, choices = [u/2, u, 2u] of the
                          config's own sweep.unresolved_stall_cycles u (approved per-branch stalls)
and copies the Stage-2 keys (reg_naming, fanout_v2, branch_cond, interleave, fpr) for provenance.
Rows not run: E5 (no config), E6/E7/E11 (Recon/SPT families), E10 (no config; predictor DECIDE).

Usage (from the code root): python3 runconfigs/twostage_fv2_20261109/make_campaign_configs.py --sample 0.01 --jobs 2
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, ".")
import pipeline  # noqa: E402

HERE = Path("runconfigs/twostage_fv2_20261109")
ROWS = [  # row, base config, scheme override
    ("E1", "runconfigs/fixed_20261030/STT_6_reconmodded_fixed_latest.jsonc", 0),
    ("E2", "runconfigs/fixed_20261030/STT_6_reconmodded_fixed_latest.jsonc", None),
    ("E3", "runconfigs/fixed_20261030/STT_6_sttmaster_fixed_latest.jsonc", None),
    ("E4", "runconfigs/amulet_parity/run_config_STT_6_amuletstt_amulet_parity.jsonc", None),
    ("E8", "runconfigs/fixed_20261030/STT_6_reconmodded_fixed_latest.jsonc", 1),
    ("E9", "runconfigs/fixed_20261030/STT_6_reconmodded_fixed_latest.jsonc", 3),
    ("E12a", "runconfigs/footprint/run_config_STT_6_invisispec_futuristic_footprint.jsonc", None),
    ("E12b", "runconfigs/footprint/run_config_STT_6_invisispec_spectre_footprint.jsonc", None),
    ("E13", "runconfigs/footprint/run_config_STT_6_cleanupspec_footprint.jsonc", None),
    ("E14", "runconfigs/footprint/run_config_STT_6_speclfb_footprint.jsonc", None),
]
TESTSETS = {"STT_6_fv2": HERE / "stage2_STT_6_fv2.jsonc", "STT_6_fv2fp": HERE / "stage2_STT_6_fv2fp.jsonc"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample", type=float, default=0.01)
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--expected", type=int, default=93041,
                    help="XMLs in the testset; testrun.py treats the campaign as complete when asm reaches alloy.max_instances")
    a = ap.parse_args()
    out = []
    for ts, s2path in TESTSETS.items():
        s2 = pipeline.load_config(s2path)
        for row, base, scheme in ROWS:
            cfg = pipeline.load_config(Path(base))
            cfg["paths"]["testset_dir"] = "testsets_twostage"
            cfg["paths"]["results_name"] = f"{row}_{ts}"
            cfg["paths"]["instruction_tables"] = s2["paths"]["instruction_tables"]
            g = cfg.setdefault("gem5", {})
            if scheme is not None:
                g["scheme"] = scheme
                if any("--scheme" in x for x in g.get("extra_args", [])):
                    raise SystemExit(f"{row}: base extra_args carries --scheme; refusing to override")
            g["sample_fraction"] = a.sample
            cfg.setdefault("alloy", {})["max_instances"] = a.expected
            g["jobs"] = a.jobs
            sw = cfg.setdefault("sweep", {})
            if sw.get("enabled"):
                u = int(sw.get("unresolved_stall_cycles", 5000))
                sw["unresolved_stall_per_branch"] = {"mode": "random", "choices": [u // 2, u, 2 * u], "seed": 0}
            for k in ("reg_naming", "fanout_v2", "branch_cond", "interleave", "fpr"):
                if k in s2:
                    cfg[k] = s2[k]
                else:
                    cfg.pop(k, None)
            hdr = (f"// {row} on {ts}: generated by make_campaign_configs.py (simspect-c8, 2026-11-09) from {base} "
                   f"(sha256 {hashlib.sha256(Path(base).read_bytes()).hexdigest()[:16]}) + {s2path.name}; "
                   f"only the keys listed in the generator's docstring differ.\n")
            p = HERE / f"{row}_{ts}.jsonc"
            p.write_text(hdr + json.dumps(cfg, indent=2) + "\n")
            out.append((row, ts, str(p)))
    (HERE / "campaigns.json").write_text(json.dumps(
        [{"row": r, "model": t, "config": c, "results_name": f"{r}_{t}"} for r, t, c in out], indent=1))
    print(f"{len(out)} configs -> {HERE}")


if __name__ == "__main__":
    main()
