#!/usr/bin/env python3
"""build_queries.py — (re)build every Alloy query that validates SKELETON_u.als.

Rerunnable; writes only into this queries/ directory (q_*.als). Sources are read only:
  ../STT_6_skel_demo.als            SKELETON_u + the STT_6 block (assembled by derive_core_u.py)
  ../../../STT_6.als                the reference model (sha256 7a6ac4c0...)
  ../../../../models/proposed_twophase/STT_6_core_ri.als   the current RI-only STT core
Run each with runq_u.sh (one java at a time, shared lock). Meaning of each query is in
its header comment and in QUERIES below.
"""
import re
from pathlib import Path

Q = Path(__file__).resolve().parent
U = Q.parent
MODELS = U.parent.parent
DEMO = (U / "STT_6_skel_demo.als").read_text()
STT6 = (MODELS / "STT_6.als").read_text()
CORE_OLD = (MODELS / "proposed_twophase" / "STT_6_core_ri.als").read_text()

SC = "exactly 1 rBool, exactly 1 cBool, exactly 1 tBool"


def run_region(text, new):
    lines = text.split("\n")
    b = [k for k, l in enumerate(lines) if l.strip().startswith("//@@RUN-BEGIN")]
    e = [k for k, l in enumerate(lines) if l.strip().startswith("//@@RUN-END")]
    assert len(b) == 1 and len(e) == 1
    return "\n".join(lines[:b[0] + 1] + new.split("\n") + lines[e[0]:])


def drop_fact(text, name):
    pat = re.compile(r"^fact " + name + r"\b[^\n]*\n", re.M)
    assert len(pat.findall(text)) == 1, name
    return pat.sub(f"// [query] fact {name} turned off here\n", text)


def write(name, text, what):
    (Q / name).write_text(f"// QUERY {name}: {what}\n// generated by queries/build_queries.py; do not edit by hand\n" + text)


# ---------------------------------------------------------------------------
# STT_6.als semantics, copied verbatim with an o6_ prefix (only what differs or
# depends on something that differs). Used by q_sem_eq / q_struct_eq.
O6 = r"""
// ===================== STT_6.als semantics (verbatim, o6_ prefix) =====================
fun o6_spo_p[p : PTag->univ] : Instruction->Instruction {spo.(iden :> (p[RI])).spo + (i_p[p] <: spo :> i_p[p])}
fun o6_fix_rf_hole_p[p : PTag->univ] : Operand -> Operand {(opstate.Reg_s<:(rf.(ddi:>(p[RI].operands)).rf):>opstate.Reg_s) + (opstate.Mem_s<:(rf.(ddi:>(p[RI].operands)).rf):>opstate.Mem_s)}
fun o6_rf_p[p : PTag->univ] : Operand -> Operand {o_p[p]<:rf:>o_p[p] + o6_fix_rf_hole_p[p]}
fun o6_op_edges_p[p: PTag->univ] : Operand -> Operand {o6_rf_p[p] + ddi_p[p]}
fun o6_f[p: PTag->univ] : Instruction {(i_p[p]) - (i_p[p]).(o6_spo_p[p])}
fun o6_has_unresolved_brs_p[p: PTag->univ] : Instruction {((unresolved_p[p] & (Branchxs+Branchns)).(^(o6_spo_p[p])))}
fun o6_no_unresolved_brs_p[p: PTag->univ] : Instruction {i_p[p] - o6_has_unresolved_brs_p[p]}
fun o6_no_unresolved_brs_bf_or_is_p[p: PTag->univ] : Instruction {o6_no_unresolved_brs_p[p] - (unresolved_p[p] & (Branchxs+Branchns))}
fun o6_speculation_contract_p[p: PTag->univ] : Instruction {uncommitted_p[p] & o6_has_unresolved_brs_p[p]}
fun o6_speculative_xmit_p[p: PTag->univ] : Operand {leakage_function_p[p] <: o6_speculation_contract_p[p].operands}
fun o6_prot_set_propagation_p[p:PTag->univ,i:Instruction,s:State] : State {
	s - (Loads & o6_no_unresolved_brs_bf_or_is_p[p] & i).inmem.opstate
}
fun o6_a[p:PTag->univ,i:Instruction,s:State] : State { o6_prot_set_propagation_p[p,i,s]}
fun o6_lcp[p: PTag->univ] : State {
		o6_a[p,o6_f[p].(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]),
o6_a[p,o6_f[p].(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]),
o6_a[p,o6_f[p].(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]),
o6_a[p,o6_f[p].(o6_spo_p[p]).(o6_spo_p[p]).(o6_spo_p[p]),
o6_a[p,o6_f[p].(o6_spo_p[p]).(o6_spo_p[p]),
			o6_a[p,o6_f[p].(o6_spo_p[p]),
				o6_a[p,o6_f[p],Mem_s]
			]
	]
]]]]
}
pred o6_secure[p: PTag->univ] {
	(no (o6_lcp[p].(~opstate) & o6_speculative_xmit_p[p])) and
	(no o6_lcp[p].(~opstate).(^(o6_op_edges_p[p])) & o6_speculative_xmit_p[p])
}
pred o6_tag {
	(some (o6_lcp[no_p].(~opstate) & o6_speculative_xmit_p[no_p] & xm.operands)) or
	(some o6_lcp[no_p].(~opstate).(^(o6_op_edges_p[no_p])) & o6_speculative_xmit_p[no_p] & xm.operands)
}
pred o6_gen {
  not o6_secure[no_p]
  all i: (unresolved - first_uncommitted) | o6_secure[RR->i]
  o6_secure[RC->first_uncommitted + RR->first_uncommitted]
  all s: State | o6_secure[RS->s]
}
pred o6_gen_core { o6_gen  all i: Instruction | o6_secure[RI->i] }
pred same[p: PTag->univ] { secure_speculation_scheme_p[p] <=> o6_secure[p] }
"""

# 1. semantic equivalence of the leak predicate, one check per perturbation family, sizes 1..6
#    (gen_useful_litmus / gen_core / tag_xm equality follow from these; q_sem_eq_gen checks them directly)
SEM = {
    "nop":  "same[no_p]\n  tag_xm_p <=> o6_tag",
    "RR":   "all i: Instruction | same[RR->i]",
    "RC":   "same[RC->first_uncommitted + RR->first_uncommitted]\n  same[RC->first_uncommitted]",
    "RS":   "all s: State | same[RS->s]",
    "RI":   "all i: Instruction | same[RI->i]",
    "RO":   "all o: Operand | same[RO->o]",
    "gen":  "gen_useful_litmus <=> o6_gen\n  gen_core <=> o6_gen_core",
}
for key, body in SEM.items():
    sem = drop_fact(DEMO, "tag_xm")
    sem = run_region(sem, f"check sem_eq_{key} {{\n  {body}\n}} for 9 but 6 Instruction, {SC}") + O6
    write(f"q_sem_eq_{key}.als", sem,
          f"SKELETON_u+STT_6 block vs STT_6.als semantics, perturbation family {key}: secure[p] equal "
          "(facts = the new (W)(V) facts, tag_xm off). Expect 0 counterexamples.")

# 2. structural pieces: spo_p, rf bridge, nonspeculative loads (one combined check; passed 2026-11-09, 465 s)
st = drop_fact(DEMO, "tag_xm")
st = run_region(st, f"""check struct_eq {{
  spo_p[no_p] = spo
  all i: Instruction | spo_p[RI->i] = o6_spo_p[RI->i]
  all i: Instruction | rf_bridge_p[RI->i] = o6_fix_rf_hole_p[RI->i]
  all i: Instruction | Loads & nonspeculative_p[RR->i] = Loads & o6_no_unresolved_brs_bf_or_is_p[RR->i]
  Loads & nonspeculative_p[no_p] = Loads & o6_no_unresolved_brs_bf_or_is_p[no_p]
  Loads & nonspeculative_p[RC->first_uncommitted + RR->first_uncommitted] = Loads & o6_no_unresolved_brs_bf_or_is_p[RC->first_uncommitted + RR->first_uncommitted]
  all i: Instruction | Loads & nonspeculative_p[RI->i] = Loads & o6_no_unresolved_brs_bf_or_is_p[RI->i]
  all s: State | Loads & nonspeculative_p[RS->s] = Loads & o6_no_unresolved_brs_bf_or_is_p[RS->s]
}} for 9 but 6 Instruction, {SC}""") + O6
write("q_struct_eq.als", st, "spo_p / rf_bridge_p / nonspeculative loads equal STT_6's spo_p / fix_rf_hole_p / "
      "no_unresolved_brs_bf_or_is_p for every single perturbation used. Expect 0.")

# 3. changed facts: old (#-based caps, old committed_last, idx bijection) vs new
facts_pred = r"""
// ===================== changed facts as predicates (query only) =====================
pred n_changed {
  all o: Operand | one o.(~operands)
  all i: Instruction | all a: i.inreg | lone (i.inreg - a)
  all i: Instruction | lone i.inaddr
  all i: Instruction | lone i.inmem
  all i: Instruction | all a: i.ins | lone (i.ins - a)
  all i: Instruction | lone i.outs
  no uncommitted <: ^spo :> committed
  one xm
  all disj a, b: Instruction | a.idx != b.idx
  (Instruction.idx).(~ix_next) in Instruction.idx
  all disj a, b: Instruction | (b in a.^spo) <=> (b.idx in a.idx.^ix_next)
}
pred lt_ix[a, b: univ] { (a=IX0 and b in IX1+IX2+IX3+IX4+IX5)
				or (a=IX1 and b in IX2+IX3+IX4+IX5)
				or (a=IX2 and b in IX3+IX4+IX5)
				or (a=IX3 and b in IX4+IX5)
				or (a=IX4 and b=IX5)
}
pred o6_changed {
  all o: Operand | #(o.(~operands)) = 1
  all i: Instruction | #(i.inreg) <= 2
  all i: Instruction | #(i.inaddr) <= 1
  all i: Instruction | #(i.inmem) <= 1
  all i: Instruction | #(i.ins) <= 2
  all i: Instruction | #(i.(outreg+outmem)) <= 1
  no ^(spo :>uncommitted).^(spo :> committed) and (no uncommitted <: ^spo :> committed)
  no (unresolved & committed)
  #(xm) = 1
  all disj a, b: Instruction | a.idx != b.idx
  (IX0 + IX1 + IX2 + IX3 + IX4 + IX5) = Instruction.idx
  all disj a, b: Instruction | lt_ix[a.idx, b.idx] <=> b in a.^spo
}
// an instruction with >= 8 operands: the only place 4-bit Int # can wrap
pred big8 { some i: Instruction | some disj o1, o2, o3, o4, o5, o6, o7, o8: i.operands | o1 = o1 }
"""
ch = DEMO
for nm in ["limited_instr_per_op", "limited_inregs", "limited_inaddrs", "limited_inmems", "limited_ins",
           "limited_outs", "committed_last", "one_xm", "idx_injective", "idx_prefix", "tag_xm"]:
    ch = drop_fact(ch, nm)
ch = re.sub(r"^fact idx_matches_spo \{\n\tall disj a, b: Instruction \| \(b in a\.\^spo\) <=> \(b\.idx in a\.idx\.\^ix_next\)\n\}\n",
            "// [query] fact idx_matches_spo turned off here\n", ch, flags=re.M)
assert not re.search(r"^fact idx_matches_spo", ch, re.M)
facts_q = run_region(ch, f"check facts_eq {{ o6_changed <=> n_changed }} for 9 but exactly 6 Instruction, {SC}") + facts_pred
write("q_facts_eq.als", facts_q, "STT_6's changed facts (#-caps, committed_last, committed_in_resolved, #xm, idx "
      "bijection) vs SKELETON_u's, at exactly 6. Expect a counterexample ONLY via Int wrap (see q_facts_eq_nobig).")
facts_q2 = run_region(ch, f"check facts_eq_nobig {{ not big8 => (o6_changed <=> n_changed) }} for 9 but exactly 6 Instruction, {SC}") + facts_pred
write("q_facts_eq_nobig.als", facts_q2, "as q_facts_eq but excluding instructions with >= 8 operands. Expect 0.")

# 4. Int-wrap witnesses on the UNMODIFIED STT_6.als semantics (a copy + a first run command)
OVER = "some i: Instruction | not (all a: i.ins | lone (i.ins - a))"
for nm, body, scope, what in [
    ("q_overflow_stt6_facts.als", OVER, "for 9 but exactly 6 Instruction",
     "STT_6.als facts (incl. tag_xm) admit an instruction with > 2 inputs? SAT = the #-caps wrap at production scope"),
    ("q_overflow_stt6_gen.als", "gen_useful_litmus\n  " + OVER, "for 9 but exactly 6 Instruction",
     "same, under gen_useful_litmus (could it reach a production testset?)"),
    ("q_overflow_stt6_gen12.als", "gen_useful_litmus\n  " + OVER, "for 12 but exactly 6 Instruction",
     "same at 12 operands (stage15-bound S3 reproduction)"),
]:
    t = STT6.replace("run gen_lit {", f"run overflow {{\n  {body}\n}} {scope}, {SC}\n\nrun gen_lit {{", 1)
    write(nm, t, what)

# 4b. the same Int-wrap witness on the production SPT model (SPT protects a load's output even
#     without a memory read, so 1 load operand + an 8-input instruction fits in 9 operands)
SPTV2 = (MODELS / "SPT_6_oneLP_v2.als").read_text()
t = SPTV2.replace("run gen_lit {", f"run overflow {{\n  gen_useful_litmus\n  {OVER}\n}} for 9 but exactly 6 Instruction, {SC}\n\nrun gen_lit {{", 1)
assert t != SPTV2
write("q_overflow_sptv2_gen.als", t, "SPT_6_oneLP_v2.als (production SPT) under gen_useful_litmus at its production scope: an instruction with > 2 inputs? SAT = the #-caps wrap reaches production SPT instances")

# 5. paper relaxation claims, on the demo (flat) and the demo core
REL = [
    ("q_rel_RI_flat.als", "gen_useful_litmus\n  some i: Instruction | not secure_speculation_scheme_p[RI->i]", "exactly 6",
     "flat / Stage-1.5 instances where removing an instruction still leaks (RI NOT enforced). Expect SAT"),
    ("q_rel_RO_flat.als", "gen_useful_litmus\n  some o: Operand | not secure_speculation_scheme_p[RO->o]", "exactly 6",
     "flat instances where removing an operand still leaks (RO NOT enforced). Expect SAT"),
    ("q_rel_RO_core.als", "gen_core\n  some o: Operand | not secure_speculation_scheme_p[RO->o]", "6",
     "RI-only Stage-1 cores where removing an operand still leaks (RO NOT enforced in cores). Expect SAT"),
    ("q_rel_RC_alone.als", "gen_useful_litmus\n  not secure_speculation_scheme_p[RC->first_uncommitted]", "exactly 6",
     "commit alone (without resolve) at the boundary still leaks: RC is only tested jointly with RR. Expect SAT"),
    ("q_rel_boundary.als", "gen_useful_litmus\n  first_uncommitted not in (unresolved & Branches)", "exactly 6",
     "is the commit boundary always the unresolved gating branch? UNSAT = yes"),
    ("q_rel_flags.als", "gen_useful_litmus\n  some (unresolved - Branches)", "exactly 6",
     "an unresolved non-branch in a generated instance (irrelevant-flag duplicates, URGENT_TODO:76)? UNSAT = none"),
    ("q_rel_RS_flat.als", "gen_useful_litmus\n  some s: State | not secure_speculation_scheme_p[RS->s]", "exactly 6",
     "sanity: RS is enforced (expect UNSAT)"),
    ("q_ri_shadowed_writer_core.als", "gen_core\n  some i: Instruction, z: Instruction - i | some (i.outs.rf) and some (z.outs.opstate & i.outs.opstate) and z -> i in ^spo", "6",
     "RI-only cores where an instruction RI removes is an rf producer and an OLDER writer of the same state survives (the perturbed program would read it; rf_p does not recompute it). SAT = RI-minimality is approximate there"),
    ("q_p5_unfed_flat.als", "gen_useful_litmus\n  not rf_complete", "exactly 6",
     "generated instances with an unfed read (P5 off). Expect SAT"),
]
for nm, body, k, what in REL:
    t = run_region(DEMO, f"run rel {{\n  {body}\n}} for 9 but {k} Instruction, {SC}")
    write(nm, t, what)

# 6. counts at small exhaustible scopes: demo flat and core (prefix idx) vs the current core (no idx)
for k in (3, 4, 5):
    write(f"q_demo_core_b{k}.als", run_region(DEMO, f"run gen_lit {{\n  gen_core\n}} for 9 but {k} Instruction, {SC}"),
          f"SKELETON_u RI-only core (prefix idx kept) up to {k} instructions: count / exhaustion")
    old = CORE_OLD.replace(f"}} for 9 but 6 Instruction, {SC}", f"}} for 9 but {k} Instruction, {SC}", 1)
    assert old != CORE_OLD
    write(f"q_old_core_b{k}.als", old, f"current STT_6_core_ri.als (idx stripped) up to {k} instructions: count / exhaustion")
for k in (3, 4):
    write(f"q_demo_flat_e{k}.als", run_region(DEMO, f"run gen_lit {{\n  gen_useful_litmus\n}} for 9 but exactly {k} Instruction, {SC}"),
          f"SKELETON_u flat generator at exactly {k} (prefix idx): count")
    write(f"q_demo_flat_e{k}_p5.als", run_region(DEMO, f"run gen_lit {{\n  gen_useful_litmus\n  rf_complete\n}} for 9 but exactly {k} Instruction, {SC}"),
          f"as q_demo_flat_e{k} with P5 rf_complete: count")

# STT_6.als at exactly 3 needs its idx block trimmed to 3 atoms (mechanical; semantics otherwise verbatim)
def stt6_at(k):
    t = STT6
    atoms = "".join(f"one sig IX{j} {{}}\n" for j in range(k))
    t = re.sub(r"one sig IX0 \{\}.*?one sig IX5 \{\}[^\n]*\n", atoms, t, flags=re.S)
    union = " + ".join(f"IX{j}" for j in range(k))
    t = t.replace("idx: one (IX0 + IX1 + IX2 + IX3 + IX4 + IX5)", f"idx: one ({union})")
    t = t.replace("fact idx_surjective { (IX0 + IX1 + IX2 + IX3 + IX4 + IX5) = Instruction.idx }",
                  f"fact idx_surjective {{ ({union}) = Instruction.idx }}")
    lt = " or ".join(f"(a=IX{j} and b in {' + '.join(f'IX{m}' for m in range(j+1, k))})" for j in range(k - 1))
    t = re.sub(r"pred lt_ix\[a, b: univ\] \{.*?\n\n\}\n", f"pred lt_ix[a, b: univ] {{ {lt} }}\n", t, flags=re.S)
    t = t.replace(f"}} for 9 but exactly 6 Instruction, {SC}", f"}} for 9 but exactly {k} Instruction, {SC}")
    assert "IX5" not in t or k == 6
    return t
for k in (3, 4):
    write(f"q_stt6_flat_e{k}.als", stt6_at(k), f"STT_6.als (idx trimmed to {k} atoms, nothing else) at exactly {k}: count")

print("built:", sorted(p.name for p in Q.glob("q_*.als")))
